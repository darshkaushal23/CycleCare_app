export function t(lang, path) {
  const parts = path.split(".");
  let node = copy[lang] ?? copy.en;
  for (const part of parts) {
    node = node?.[part];
  }
  if (node == null) {
    node = copy.en;
    for (const part of parts) node = node?.[part];
  }
  return node ?? path;
}
